import { ApiBase } from '../../app/api-base';
import { ChapterService } from '../orthography/chapter-service';
import { MorphologyService } from '../morphology/morphology-service';
import { Location, formatLocation } from '../orthography/location';
import { Verse } from '../orthography/verse';
import { Graph } from './syntax-graph';
import { GraphLocation } from './graph-location';
import { Word } from './word';
import { DraftGraph, DraftWord, getDraftVerseNumber, readDraftGraphs } from './draft-graph-reader';
import { CorpusError } from '../../errors/corpus-error';
import { singleton } from 'tsyringe';
import axios, { AxiosError } from 'axios';
import drafts from './treebank-drafts.json';

type DraftChapter = {
    chapterNumber: number,
    firstVerse: number,
    lastVerse: number,
    lastVerseGraphs: number,
    verses: number,
    words: number,
    graphs: number
}

// Draft syntax graphs are generated by a parser and have not been reviewed. They are kept apart
// from the verified treebank served by the API: one text file per chapter in public/treebank-drafts,
// listed in treebank-drafts.json. See docs/treebank-drafts.md.
@singleton()
export class DraftSyntaxService extends ApiBase {
    readonly chapters: DraftChapter[] = drafts.chapters;
    private readonly chapterMap = new Map(this.chapters.map(chapter => [chapter.chapterNumber, chapter]));
    private readonly chapterGraphs = new Map<number, Promise<DraftGraph[]>>();

    constructor(
        private readonly chapterService: ChapterService,
        private readonly morphologyService: MorphologyService) {
        super();
    }

    hasDraft([chapterNumber, verseNumber]: Location) {
        const chapter = this.chapterMap.get(chapterNumber);
        return chapter !== undefined && verseNumber >= chapter.firstVerse && verseNumber <= chapter.lastVerse;
    }

    async getGraph({ location, graphNumber }: GraphLocation): Promise<Graph | undefined> {
        if (!this.hasDraft(location)) return undefined;

        const [chapterNumber, verseNumber] = location;
        const graphs = await this.getChapterGraphs(chapterNumber);
        const verseStart = graphs.findIndex(graph => getDraftVerseNumber(graph) === verseNumber);
        if (verseStart < 0) return undefined;

        let graphCount = 1;
        while (verseStart + graphCount < graphs.length
            && getDraftVerseNumber(graphs[verseStart + graphCount]) === verseNumber) {
            graphCount++;
        }
        if (graphNumber < 1 || graphNumber > graphCount) return undefined;

        const index = verseStart + graphNumber - 1;
        const draft = graphs[index];
        const [verse] = await this.morphologyService.getMorphology([chapterNumber, verseNumber], 1, []);

        return {
            graphNumber,
            graphCount,
            legacyCorpusGraphNumber: 0,
            prev: index > 0
                ? this.getDraftLocation(chapterNumber, graphs, index - 1)
                : await this.getLastGraphLocation(this.getPrecedingVerse(location)),
            next: index < graphs.length - 1
                ? this.getDraftLocation(chapterNumber, graphs, index + 1)
                : this.getFirstGraphLocation(this.getFollowingVerse(location)),
            words: draft.words.map(word => this.getWord(word, verse)),
            edges: draft.edges,
            phraseNodes: draft.phraseNodes,
            draft: true
        };
    }

    // The API links each verified graph to the next verified graph. Where a draft lies in
    // between, link to the draft instead.
    linkDrafts({ location }: GraphLocation, graph: Graph): Graph {
        let { prev, next } = graph;

        if (graph.graphNumber === graph.graphCount) {
            const following = this.getFollowingVerse(location);
            if (following && this.hasDraft(following)) {
                next = this.getFirstGraphLocation(following);
            }
        }

        if (graph.graphNumber === 1) {
            const preceding = this.getPrecedingVerse(location);
            const chapter = preceding && this.chapterMap.get(preceding[0]);
            if (chapter && preceding[1] === chapter.lastVerse) {
                prev = { location: preceding, graphNumber: chapter.lastVerseGraphs };
            }
        }

        return { ...graph, prev, next };
    }

    private getChapterGraphs(chapterNumber: number) {
        let graphs = this.chapterGraphs.get(chapterNumber);
        if (!graphs) {
            const file = `${String(chapterNumber).padStart(3, '0')}.txt`;
            graphs = axios
                .get(`${import.meta.env.BASE_URL}treebank-drafts/${file}`, { responseType: 'text' })
                .then(response => readDraftGraphs(response.data as string));
            this.chapterGraphs.set(chapterNumber, graphs);
        }
        return graphs;
    }

    private getWord(word: DraftWord, verse: Verse): Word {
        const { type, location, elidedText, elidedPosTag, startNode, endNode } = word;
        if (!location) {
            return { type, elidedText, elidedPosTag, startNode, endNode };
        }

        const token = verse.tokens[location[2] - 1];
        const nodeCount = token.segments.filter(segment => segment.posTag !== 'DET').length;
        if (nodeCount !== endNode - startNode + 1) {
            throw new CorpusError(
                'SERVICE_ERROR',
                `Draft graph does not match the morphology of word ${formatLocation(location)}.`);
        }
        return { type, token, startNode, endNode };
    }

    private getDraftLocation(chapterNumber: number, graphs: DraftGraph[], index: number): GraphLocation {
        const verseNumber = getDraftVerseNumber(graphs[index]);
        let graphNumber = 1;
        while (index - graphNumber >= 0 && getDraftVerseNumber(graphs[index - graphNumber]) === verseNumber) {
            graphNumber++;
        }
        return { location: [chapterNumber, verseNumber], graphNumber };
    }

    private getFirstGraphLocation(location?: Location): GraphLocation | undefined {
        return location && { location, graphNumber: 1 };
    }

    private async getLastGraphLocation(location?: Location): Promise<GraphLocation | undefined> {
        if (!location) return undefined;

        const chapter = this.chapterMap.get(location[0]);
        if (chapter && location[1] === chapter.lastVerse) {
            return { location, graphNumber: chapter.lastVerseGraphs };
        }

        // a verified verse: ask the API how many graphs it has
        try {
            const response = await axios.get(
                this.url('/syntax'),
                { params: { location: formatLocation(location), graph: 1 } });
            return { location, graphNumber: (response.data as Graph).graphCount };
        } catch (e) {
            if (e instanceof AxiosError && e.response?.status === 404) return undefined;
            throw e;
        }
    }

    private getFollowingVerse([chapterNumber, verseNumber]: Location): Location | undefined {
        if (verseNumber < this.chapterService.getChapter(chapterNumber).verseCount) {
            return [chapterNumber, verseNumber + 1];
        }
        return chapterNumber < this.chapterService.chapters.length ? [chapterNumber + 1, 1] : undefined;
    }

    private getPrecedingVerse([chapterNumber, verseNumber]: Location): Location | undefined {
        if (verseNumber > 1) {
            return [chapterNumber, verseNumber - 1];
        }
        return chapterNumber > 1
            ? [chapterNumber - 1, this.chapterService.getChapter(chapterNumber - 1).verseCount]
            : undefined;
    }
}
