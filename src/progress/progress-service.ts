import { singleton } from 'tsyringe';
import coverage from './annotation-coverage.json';
import drafts from '../corpus/syntax/treebank-drafts.json';

export type Progress = {
    count: number,
    total: number
}

export type ChapterCoverage = {
    words: number,
    verses: number,
    treebankWords: number,
    treebankVerses: number,
    draftWords: number,
    draftVerses: number
}

type DraftChapter = {
    chapterNumber: number,
    verses: number,
    words: number
}

// Annotation coverage is measured from the corpus data files by scripts/annotation-coverage.mjs.
// Draft syntax graphs are generated by a parser and are counted apart from the verified treebank.
@singleton()
export class ProgressService {
    readonly sourceUrl: string = coverage.source;
    readonly sourceDate = new Date(coverage.date);
    readonly chapters: ChapterCoverage[];

    constructor() {
        const draftChapters: DraftChapter[] = drafts.chapters;
        const draftMap = new Map(draftChapters.map(chapter => [chapter.chapterNumber, chapter]));
        this.chapters = coverage.chapters.map((chapter, i) => {
            const draft = draftMap.get(i + 1);
            return {
                ...chapter,
                draftWords: draft?.words ?? 0,
                draftVerses: draft?.verses ?? 0
            };
        });
    }

    getChapterCoverage(chapterNumber: number): ChapterCoverage {
        return this.chapters[chapterNumber - 1];
    }

    get morphologyWords(): Progress {
        return { count: coverage.morphologyWords, total: this.sum('words') };
    }

    get treebankWords(): Progress {
        return { count: this.sum('treebankWords'), total: this.sum('words') };
    }

    get treebankVerses(): Progress {
        return { count: this.sum('treebankVerses'), total: this.sum('verses') };
    }

    get draftWords(): Progress {
        return { count: this.sum('draftWords'), total: this.sum('words') };
    }

    get draftVerses(): Progress {
        return { count: this.sum('draftVerses'), total: this.sum('verses') };
    }

    get treebankChapters(): Progress {
        return {
            count: this.chapters.filter(chapter => chapter.treebankWords === chapter.words).length,
            total: this.chapters.length
        };
    }

    private sum(key: keyof ChapterCoverage) {
        return this.chapters.reduce((sum, chapter) => sum + chapter[key], 0);
    }
}
